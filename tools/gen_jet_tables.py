"""Generate firmware/src/jet_tables.h — KO JET fixed-point LUTs."""
from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "src" / "jet_tables.h"

FS = 44100.0
A440 = 440.0


def q15(x: float) -> int:
    v = int(round(x * 32768.0))
    if v > 32767:
        v = 32767
    if v < -32768:
        v = -32768
    return v


def emit_array(name: str, vals: list[int], per_line: int = 8) -> list[str]:
    lines = [f"static const int16_t {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per_line):
        chunk = vals[i : i + per_line]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
    lines.append("};")
    return lines


def emit_array_u32(name: str, vals: list[int], per_line: int = 6) -> list[str]:
    lines = [f"static const uint32_t {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per_line):
        chunk = vals[i : i + per_line]
        lines.append("    " + ", ".join(f"{v}u" for v in chunk) + ",")
    lines.append("};")
    return lines


def main() -> int:
    # JET_OP_A_Q15[128]: one-pole a = 1 - exp(-2*pi*f/fs), MIDI pitch m = index
    op_a: list[int] = []
    for m in range(128):
        f = A440 * (2.0 ** ((m - 69) / 12.0))
        if f < 1.0:
            f = 1.0
        a = 1.0 - math.exp(-2.0 * math.pi * f / FS)
        op_a.append(q15(a))

    # JET_EXP2_FRAC_Q15[257]: 2^(-i/256)
    exp2_frac: list[int] = []
    for i in range(257):
        exp2_frac.append(q15(2.0 ** (-i / 256.0)))

    # JET_LEN_OCT_Q16[1201]: period samples Q16, C0 + cents over one octave
    f_c0 = A440 * (2.0 ** ((12 - 69) / 12.0))
    len_oct: list[int] = []
    for cent in range(1201):
        f = f_c0 * (2.0 ** (cent / 1200.0))
        per = (FS / f) * 65536.0
        v = int(round(per))
        if v < 8 * 65536:
            v = 8 * 65536
        len_oct.append(v)

    # JET_THIRAN_Q15[257]: eta = (1-d)/(1+d), d in [0.5, 1.5)
    thiran: list[int] = []
    for i in range(257):
        d = 0.5 + i / 256.0
        eta = (1.0 - d) / (1.0 + d)
        thiran.append(q15(eta))

    # JET_TANH_Q15[1025]: tanh on [-4, 4]
    tanh_lut: list[int] = []
    for i in range(1025):
        x = -4.0 + (8.0 * i / 1024.0)
        tanh_lut.append(q15(math.tanh(x)))

    # JET_T60_INV_Q24[128]: 1/(T*fs), T log-spaced 10 ms .. 20 s (match bass time law shape)
    t60_inv: list[int] = []
    t_min = 0.010
    t_max = 20.0
    for v in range(128):
        if v == 0:
            t = t_min
        else:
            t = t_min * ((t_max / t_min) ** (v / 127.0))
        inv = 1.0 / (t * FS)
        q = int(round(inv * (1 << 24)))
        if q < 1:
            q = 1
        if q > 0x7FFFFFFF:
            q = 0x7FFFFFFF
        t60_inv.append(q)

    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* AUTO-GENERATED by tools/gen_jet_tables.py — do not edit */",
        "#ifndef JET_TABLES_H",
        "#define JET_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    lines.extend(emit_array("JET_OP_A_Q15", op_a))
    lines.append("")
    lines.extend(emit_array("JET_EXP2_FRAC_Q15", exp2_frac))
    lines.append("")
    lines.extend(emit_array_u32("JET_LEN_OCT_Q16", len_oct))
    lines.append("")
    lines.extend(emit_array("JET_THIRAN_Q15", thiran))
    lines.append("")
    lines.extend(emit_array("JET_TANH_Q15", tanh_lut))
    lines.append("")
    lines.extend(emit_array_u32("JET_T60_INV_Q24", t60_inv))
    lines.append("")
    lines.append("#endif /* JET_TABLES_H */")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
