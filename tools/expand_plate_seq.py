def expand_block(text: str, array_name: str, new_rows: list[str], n_old: int) -> str:
    pat = rf"(static const dub_plate_seq_t {array_name}\[GENRE_PRESET_N\] = \{{)(.*?)(\n\}};)"
    m = re.search(pat, text, re.S)
    if not m:
        raise SystemExit(f"{array_name} not found")
    rows = [ln for ln in m.group(2).splitlines() if ln.strip().startswith("{")]
    if len(rows) != n_old:
        raise SystemExit(f"{array_name}: expected {n_old} rows, got {len(rows)}")
    eras = n_old // OLD
    out: list[str] = []
    ni = 0
    for e in range(eras):
        out.extend(rows[e * OLD : (e + 1) * OLD])
        out.extend([new_rows[ni], new_rows[ni + 1]])
        ni += 2
    body = "\n".join(out) + "\n"
    return text[: m.start(2)] + "\n" + body + text[m.end(2) :]


