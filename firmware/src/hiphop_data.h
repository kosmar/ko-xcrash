static inline uint32_t hiphop_beat_lead_gate32(uint8_t beat)
{
    if (hiphop_gen_hit(beat))
        return hiphop_gen.lead_gate;
    return HIPHOP_BEAT_LEAD_GATE[hiphop_clamp_beat(beat)];
}
static inline uint8_t hiphop_beat_lead_gate_cs(uint8_t beat)
{
    if (hiphop_gen_hit(beat))
        return hiphop_gen.gate_cs;
    return HIPHOP_BEAT_LEAD_GATE_CS[hiphop_clamp_beat(beat)];
}
static inline uint8_t hiphop_beat_lead_step_bit(uint8_t beat, uint8_t step)
{
    uint32_t g32 = hiphop_beat_lead_gate32(beat);
    uint8_t bar4 = (uint8_t)((step >> 4) & 3u);
    uint8_t s16 = (uint8_t)(step & 15u);
    if (bar4 == 0u || bar4 == 2u) return (uint8_t)((g32 >> s16) & 1u);
    if (bar4 == 1u) return (uint8_t)((g32 >> (16u + s16)) & 1u);
    if (s16 < 8u) return 0u;
    return (uint8_t)((g32 >> (16u + s16)) & 1u);
}
static inline int8_t hiphop_beat_lead_pitch(uint8_t beat, uint8_t step)
{
    if (hiphop_gen_hit(beat))
        return hiphop_gen_lead.pitch[step & 15u];
    return HIPHOP_BEAT_LEAD_PITCH[hiphop_clamp_beat(beat)][step & 15u];
}
static inline uint8_t hiphop_beat_lead_len_ix(uint8_t beat, uint8_t step)
{
    if (hiphop_gen_hit(beat))
        return hiphop_gen_lead.len[step & 31u];
    return HIPHOP_BEAT_LEAD_LEN[hiphop_clamp_beat(beat)][step & 31u];
}
static inline uint8_t hiphop_beat_lead_bend_u7(uint8_t beat, uint8_t step)
{
    if (hiphop_gen_hit(beat))
        return hiphop_gen_lead.bend[step & 31u];
    return HIPHOP_BEAT_LEAD_BEND[hiphop_clamp_beat(beat)][step & 31u];
}

static inline uint8_t dub_step_bit(uint32_t mask, uint8_t step)
{
    return (uint8_t)((mask >> (step & (DUB_STEPS - 1u))) & 1u);
}

/* Lane 3 = scratch/lead: stay dry into global delay/reverb buses. */
static inline void hiphop_scratch_fx_dry(dub_params_t *p)
{
    if (!p)
        return;
    p->drm_rev[3] = 0u;
    p->drm_dly[3] = 0u;
}

static inline void dub_drm_set_bus_dly(dub_params_t *p, uint8_t bus)
{
    uint8_t i;

    if (!p)
        return;
    for (i = 0; i < 3u; i++)
        p->drm_dly[i] = bus;
    p->drm_dly[3] = 0u;
}

static inline void dub_drm_set_bus_rev(dub_params_t *p, uint8_t bus)
{
    uint8_t i;
    /* Was 48+(bus>>1) → ~63–70 on every drum (too wet). Short room only. */
    uint8_t rv = (uint8_t)(10u + (bus >> 1));

    if (!p)
        return;
    if (rv > 36u)
        rv = 36u;
    for (i = 0; i < 3u; i++)
        p->drm_rev[i] = rv;
    p->drm_rev[3] = 0u;
}

static inline void dub_drm_voice_kit_fill(dub_params_t *p, uint8_t tune, uint8_t decay, uint8_t drive)
{
    uint8_t i;
    uint8_t t = tune ? tune : 64u;
    uint8_t d = decay ? decay : 64u;

    if (!p)
        return;
    for (i = 0; i < 4u; i++) {
        p->drm_tune[i] = t;
        p->drm_dec[i] = d;
        p->drm_drv[i] = drive;
    }
}

static inline void hiphop_apply_defaults(dub_params_t *p)
{
    uint8_t di;
    if (!p) return;
    p->timbre = 32; p->cutoff_c = 68; p->decay_c = 92; p->cutoff_b = 36; p->decay_b = 110;
    p->sub_oct = 0; p->drive = 12; p->pump = 64; p->feedback = 16; p->density = 60u; p->wobble = 10;
    p->reso_mode = 10;
    p->kick_boom = 100; p->rim_tone = 50; p->hat_lvl = 48; p->siren_pitch = 92; p->siren_rate = 40;
    p->drum_kit = DKIT_BREAK;
    for (di = 0; di < 4u; di++) {
        p->drm_tune[di]=64u; p->drm_dec[di]=72u; p->drm_drv[di]=18u;
        p->drm_cut[di]=64u; p->drm_atk[di]=0u; p->drm_dens[di]=64u;
        if (di < 3u) {
            p->drm_dly[di]=28u;
            p->drm_rev[di]=24u;
        }
    }
    hiphop_scratch_fx_dry(p);
}

