static inline uint8_t hiphop_drm_density_allows(uint8_t density, uint8_t step, uint8_t voice_ix)
{
    return ((step * 19u + (voice_ix * 37u)) & 127u) < density;
}

static inline uint8_t hiphop_gate_after_drm_density(uint8_t on, uint8_t density, uint8_t step, uint8_t voice_ix)
{
    if (!on) return 0u; return hiphop_drm_density_allows(density, step, voice_ix);
}

static inline void dub_resolve_step(const dub_params_t *p, const dub_step_t *ovr, uint8_t step, dub_events_t *out, uint8_t apply_dens)
{
    const hiphop_beat_t *drum; const hiphop_beat_t *main;
    uint8_t kick, rim, hat, sub, chord, siren, forced;
    if (!p || !out) return;
    if (step >= DUB_STEPS) step = (uint8_t)(DUB_STEPS - 1u);
    drum = hiphop_beat(p->drum_pat); main = hiphop_beat(p->plate);
    forced = (ovr != 0) && ((ovr->force & 1u) != 0);
    if (forced) {
        kick = (ovr->gate >> 0) & 1u; rim = (ovr->gate >> 1) & 1u; hat = (ovr->gate >> 2) & 1u;
        siren = (ovr->gate >> 3) & 1u; sub = (ovr->gate >> 4) & 1u; chord = (ovr->gate >> 5) & 1u;
    } else {
        kick = dub_step_bit(drum->kick, step);
        rim = dub_step_bit(drum->rim, step);
        hat = dub_step_bit(drum->hat, step);
        siren = hiphop_beat_lead_step_bit(p->plate, step);
        sub = dub_step_bit(main->sub, step);
        chord = dub_step_bit(main->chord, step);
    }
    (void)apply_dens;
    out->kick = kick; out->rim = rim; out->hat = hat; out->siren = siren; out->sub = sub; out->chord = chord;
    out->note = forced ? ovr->note : 0u; out->dly_throw = forced ? ovr->dly_throw : 0u;
    out->rev_throw = forced ? ovr->rev_throw : 0u; out->accent = forced ? ovr->accent : 0u;
}

