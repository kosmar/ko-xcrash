static inline void pop_drm_dec_fit_apply(dub_params_t *p, uint8_t preset)
{
    uint8_t i;

    if (!p || preset >= GENRE_PRESET_N)
        return;
    for (i = 0; i < 3u; i++)
        p->drm_dec[i] = pop_drm_dec_fit[preset][i];
}

static inline void pop_plate_apply(dub_params_t *p, uint8_t plate, uint8_t what)
{
    const pop_plate_t *pl;
    uint8_t di;

    if (!p)
        return;
    plate = pop_clamp_plate(plate);
    pl = pop_plate(plate);
    if ((what & DUB_APPLY_ALL) == DUB_APPLY_ALL) {
        pop_apply_defaults(p);
        pop_era_apply_base(p, pl->era);
        pop_drm_dec_fit_apply(p, plate);
    }
    p->era = pl->era;
    p->plate = plate;
    if ((what & DUB_APPLY_ALL) == DUB_APPLY_ALL) {
        p->bpm = pl->bpm;
        p->density = 64u;
        for (di = 0; di < 3u; di++)
            p->drm_dens[di] = 64u;
        p->drm_dens[3] = POP_LEAD_TIMB_DEF[pl->era];
        p->drum_kit = pop_plate_kit(plate);
        p->bass_model = pl->bass_model;
        p->voicing = pl->voicing;
        p->pump = pl->pump;
        p->wobble = pl->wobble;
        p->feedback = pl->feedback;
        p->tank = pl->tank;
        p->tap = pl->tap;
        p->dly_c = pl->dly_c;
        p->rev_c = pl->rev_c;
        p->loop_filt = pl->loop_filt;
        p->root = pop_plate_root(plate);
        p->scale = pop_plate_scale(plate);
        p->swing = pop_plate_swing(plate);
        {
            int16_t lead = (int16_t)p->siren_rate + (int16_t)pop_plate_lead_rate(plate);
            if (lead < 0)
                lead = 0;
            else if (lead > 127)
                lead = 127;
            p->siren_rate = (uint8_t)lead;
        }
        {
            int16_t tb = (int16_t)p->timbre + (int16_t)POP_PLATE_LEAD_TIMB[plate];

            if (tb < 0)
                tb = 0;
            else if (tb > 127)
                tb = 127;
            p->timbre = (uint8_t)tb;
        }
    }
}

static inline void pop_preset_rebuild(dub_params_t *p, uint8_t era, uint8_t plate)
{
    if (!p)
        return;
    era = pop_clamp_era(era);
    plate = pop_clamp_plate(plate);
    pop_plate_apply(p, plate, DUB_APPLY_ALL);
    p->era = era;
    p->plate = plate;
    p->drum_kit = pop_plate_kit(plate);
    p->bass_model = pop_plate(plate)->bass_model;
    p->voicing = pop_plate(plate)->voicing;
    p->bpm = pop_plate(plate)->bpm;
    p->pump = pop_plate(plate)->pump;
    p->feedback = pop_plate(plate)->feedback;
    p->wobble = pop_plate(plate)->wobble;
    p->drum_pat = plate;
    p->root = pop_plate_root(plate);
    p->scale = pop_plate_scale(plate);
    p->swing = pop_plate_swing(plate);
}

static inline void dub_drm_send_fixup(dub_params_t *p)
{
    uint8_t i;
    uint8_t dnz = 0u;
    uint8_t rnz = 0u;

    if (!p)
        return;
    for (i = 0; i < 4u; i++) {
        if (p->drm_dly[i])
            dnz = 1u;
        if (p->drm_rev[i])
            rnz = 1u;
    }
    if (!dnz)
        dub_drm_set_bus_dly(p, 28u);
    if (!rnz)
        dub_drm_set_bus_rev(p, 28u);
}

static inline uint8_t dub_step_bit(uint16_t mask, uint8_t step)
{
    return (uint8_t)((mask >> (step & 15u)) & 1u);
}

static inline void dub_plate_groove_read(uint8_t plate, uint8_t *root, uint8_t *scale, uint8_t *swing, uint8_t *bpm)
{
    const pop_plate_t *pl;

    plate = pop_clamp_plate(plate);
    pl = pop_plate(plate);
    if (root)
        *root = pop_plate_root(plate);
    if (scale)
        *scale = pop_plate_scale(plate);
    if (swing)
        *swing = pop_plate_swing(plate);
    if (bpm)
        *bpm = pl->bpm;
}

static inline void dub_resolve_step(const dub_params_t *p, const dub_step_t *ovr, uint8_t step,
                                    dub_events_t *out, uint8_t apply_dens)
{
    const pop_plate_t *drum;
    const pop_plate_t *main;
    uint8_t kick, rim, hat, sub, chord, siren;
    uint8_t forced;

    (void)apply_dens;
    if (!p || !out)
        return;
    if (step >= DUB_STEPS)
        step = (uint8_t)(DUB_STEPS - 1u);
    drum = pop_plate(p->drum_pat);
    main = pop_plate(p->plate);
    forced = (ovr != 0) && ((ovr->force & 1u) != 0);
    if (forced) {
        kick = (ovr->gate >> 0) & 1u;
        rim = (ovr->gate >> 1) & 1u;
        hat = (ovr->gate >> 2) & 1u;
        sub = (ovr->gate >> 3) & 1u;
        chord = (ovr->gate >> 4) & 1u;
        siren = (ovr->gate >> 5) & 1u;
    } else {
        kick = dub_step_bit(main->kick, step);
        rim = dub_step_bit(main->rim, step);
        hat = dub_step_bit(main->hat, step);
        sub = dub_step_bit(main->sub, step);
        chord = dub_step_bit(main->chord, step);
        siren = dub_step_bit(main->siren, step);
    }
    out->kick = kick;
    out->rim = rim;
    out->hat = hat;
    out->siren = siren;
    out->sub = sub;
    out->chord = chord;
    out->note = forced ? ovr->note : 0u;
    out->dly_throw = forced ? ovr->dly_throw : 0u;
    out->rev_throw = forced ? ovr->rev_throw : 0u;
    out->accent = forced ? ovr->accent : 0u;
    (void)drum;
}

