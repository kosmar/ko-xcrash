/* Live generated plate (endless continuum); shadows the ROM plate at pop_gen.slot. Root and scale stay the
 * landmark's (pop_gen.h), so the per-slot progression, melody and arrangement tables keep matching. */
static fm_pgen_t pop_gen = { .slot = 0xFFu };

#define FM_PGEN_STATE pop_gen
#define FM_PGEN_BUILD(era, n, c) pop_gen_build(era, n, c)

static inline uint8_t pop_gen_hit(uint8_t ix)
{
    return fm_pgen_hit(&pop_gen, ix);
}

static inline uint8_t pop_clamp_plate(uint8_t ix)
{
    return ix >= POP_PLATE_N ? (uint8_t)(POP_PLATE_N - 1u) : ix;
}

static inline uint8_t pop_plate_root(uint8_t ix)
{
    return pop_gen_hit(ix) ? (uint8_t)pop_gen.root : (uint8_t)POP_PLATE_ROOT[pop_clamp_plate(ix)];
}

static inline uint8_t pop_plate_scale(uint8_t ix)
{
    return pop_gen_hit(ix) ? (uint8_t)pop_gen.scale : (uint8_t)POP_PLATE_SCALE[pop_clamp_plate(ix)];
}

static inline uint8_t pop_plate_swing(uint8_t ix)
{
    return pop_gen_hit(ix) ? (uint8_t)pop_gen.swing : (uint8_t)POP_PLATE_SWING[pop_clamp_plate(ix)];
}

static inline uint8_t pop_plate_kit(uint8_t ix)
{
    return pop_gen_hit(ix) ? (uint8_t)pop_gen.kit : (uint8_t)POP_PLATE_KIT[pop_clamp_plate(ix)];
}

static inline int8_t pop_plate_lead_rate(uint8_t ix)
{
    return pop_gen_hit(ix) ? pop_gen.rate : POP_PLATE_LEAD_RATE[pop_clamp_plate(ix)];
}

static inline uint8_t pop_clamp_era(uint8_t era)
{
    return era >= POP_ERA_N ? (uint8_t)(POP_ERA_N - 1u) : era;
}

static inline const char *pop_era_name(uint8_t era)
{
    return POP_ERA_NAMES[pop_clamp_era(era)];
}

static inline const char *pop_lead_name(uint8_t era)
{
    return POP_LEAD_NAME[pop_clamp_era(era)];
}

static inline const char *pop_lead_drive(uint8_t era)
{
    return POP_LEAD_DRIVE[pop_clamp_era(era)];
}

static inline uint8_t pop_lead_variant(uint8_t plate)
{
    return POP_LEAD_VARIANT[pop_clamp_plate(plate)] & 3u;
}

static inline uint8_t pop_lead_texture(uint8_t era, uint8_t var)
{
    era = pop_clamp_era(era);
    return POP_LEAD_ER_TEX[era][var & 3u];
}

static inline int32_t pop_lead_midi_ceiling(uint8_t era, uint8_t var)
{
    era = pop_clamp_era(era);
    return pop_lead_texture(era, var) == POP_LEAD_TEX_CHOIR ? 74 : 79;
}

static inline int32_t pop_semi_octave_only(int32_t semi)
{
    if (semi >= 0)
        return (semi / 12) * 12;
    return -(((-semi) + 11) / 12) * 12;
}

static inline int32_t pop_lead_midi_floor(uint8_t era, uint8_t var)
{
    era = pop_clamp_era(era);
    return pop_lead_texture(era, var) == POP_LEAD_TEX_CHOIR ? 50 : 45;
}

static inline int32_t pop_lead_clamp_range_midi(int32_t note, int32_t floor, int32_t ceiling)
{
    while (note > ceiling)
        note -= 12;
    while (note < floor)
        note += 12;
    if (note < 0)
        note = 0;
    if (note > 127)
        note = 127;
    return note;
}

static inline int32_t pop_lead_resolve_midi_core(const dub_params_t *p, uint8_t plate, int8_t st_tune,
                                                 int8_t oct_lfo_semi, uint8_t apply_register_fix)
{
    uint8_t era = pop_clamp_era(p->era);
    uint8_t var = pop_lead_variant(plate);
    int32_t kt = pop_semi_octave_only(((int32_t)(p->drm_tune[3] ? p->drm_tune[3] : 64u) - 64) * 24 / 64);
    int32_t lead_oct = pop_semi_octave_only((int32_t)p->siren_pitch - 60);
    int32_t var_tune = (int32_t)POP_LEAD_VAR_TUNE[era][var];
    int32_t sn = (int32_t)p->root + lead_oct + kt + (int32_t)st_tune + var_tune +
                 pop_semi_octave_only((int32_t)oct_lfo_semi);

    if (apply_register_fix) {
        sn += (int32_t)POP_LEAD_REG_SHIFT_SEMI[era] + (int32_t)POP_LEAD_VAR_REG_SHIFT[era][var];
        if (POP_LEAD_VAR_OCT[era][var]) {
            int32_t ceil = pop_lead_midi_ceiling(era, var);

            if (sn + 12 <= ceil)
                sn += 12;
            else
                sn -= 12;
        }
        sn = pop_lead_clamp_range_midi(sn, pop_lead_midi_floor(era, var), pop_lead_midi_ceiling(era, var));
    } else if (POP_LEAD_VAR_OCT[era][var])
        sn += 12;
    if (sn < 0)
        sn = 0;
    if (sn > 127)
        sn = 127;
    return sn;
}


static inline const char *pop_plate_name(uint8_t ix)
{
    if (pop_gen_hit(ix))
        return pop_gen.name;
    return POP_PLATE[pop_clamp_plate(ix)].name;
}

static inline const pop_plate_t *pop_plate(uint8_t ix)
{
    if (pop_gen_hit(ix))
        return &pop_gen.pl;
    return &POP_PLATE[pop_clamp_plate(ix)];
}

static inline uint8_t pop_era_of_plate(uint8_t pl)
{
    pl = pop_clamp_plate(pl);
    return (uint8_t)(pl / GENRE_PRESETS_PER_ERA);
}

static inline uint8_t pop_lead_texture_plate(uint8_t plate)
{
    plate = pop_clamp_plate(plate);
    return pop_lead_texture(pop_era_of_plate(plate), pop_lead_variant(plate));
}

static inline uint8_t pop_era_first_plate(uint8_t era)
{
    return (uint8_t)(pop_clamp_era(era) * GENRE_PRESETS_PER_ERA);
}

static inline void pop_apply_defaults(dub_params_t *p)
{
    uint8_t di;

    if (!p)
        return;
    p->timbre = 28;
    p->cutoff_c = 52;
    p->decay_c = 36;
    p->cutoff_b = 70;
    p->decay_b = 90;
    p->sub_oct = 0;
    p->drive = 26;
    p->pump = 88;
    p->feedback = 16;
    p->density = 64u;
    p->wobble = 8;
    p->kick_boom = 78;
    p->rim_tone = 56;
    p->hat_lvl = 54;
    p->siren_pitch = 72;
    p->siren_rate = 48;
    p->drum_kit = DKIT_SILVR;
    for (di = 0; di < 4u; di++) {
        p->drm_tune[di] = 64u;
        p->drm_dec[di] = 64u;
        p->drm_drv[di] = 18u;
        p->drm_dly[di] = 28u;
        p->drm_rev[di] = 24u;
        p->drm_cut[di] = 64u;
        p->drm_atk[di] = 0u;
        if (di < 3u)
            p->drm_dens[di] = 64u;
    }
    p->drm_dens[3] = 64u;
}

static inline void dub_drm_set_bus_dly(dub_params_t *p, uint8_t bus)
{
    uint8_t i;

    if (!p)
        return;
    for (i = 0; i < 4u; i++)
        p->drm_dly[i] = bus;
}

static inline void dub_drm_set_bus_rev(dub_params_t *p, uint8_t bus)
{
    uint8_t i;
    uint8_t rv = (uint8_t)(48u + (bus >> 1));

    if (!p)
        return;
    for (i = 0; i < 3u; i++)
        p->drm_rev[i] = rv;
    p->drm_rev[3] = 96u;
}

static inline void dub_drm_voice_kit_fill(dub_params_t *p, uint8_t tune, uint8_t decay, uint8_t drive)
{
    uint8_t i;
    uint8_t t = tune ? tune : 64u;
    uint8_t d = decay ? decay : 64u;

    if (!p)
        return;
    for (i = 0; i < 4u; i++) {
        p->drm_tune[i] = t;
        p->drm_dec[i] = d;
        p->drm_drv[i] = drive;
    }
}

static inline void pop_era_apply_base(dub_params_t *p, uint8_t era)
{
    const pop_era_base_t *eb;
    const pop_era_fx_t *fx;
    uint8_t i;

    if (!p)
        return;
    era = pop_clamp_era(era);
    eb = &POP_ERA_BASE[era];
    fx = &POP_ERA_FX[era];
    p->era = era;
    p->timbre = eb->timbre;
    p->cutoff_c = eb->cutoff_c;
    p->decay_c = eb->decay_c;
    p->reso_mode = eb->reso_mode;
    p->env_filt = eb->env_filt;
    p->cutoff_b = eb->cutoff_b;
    p->decay_b = eb->decay_b;
    p->sub_oct = eb->sub_oct;
    p->drive = eb->drive;
    p->dly_b = eb->dly_b;
    p->kick_boom = eb->kick_boom;
    p->rim_tone = eb->rim_tone;
    p->hat_lvl = eb->hat_lvl;
    dub_drm_voice_kit_fill(p, eb->kit_tune, eb->kit_decay, eb->kit_drive);
    p->siren_pitch = eb->siren_pitch;
    p->siren_rate = eb->siren_rate;
    dub_drm_set_bus_dly(p, eb->rim_dly);
    dub_drm_set_bus_rev(p, eb->rim_dly);
    for (i = 0; i < 4u; i++)
        p->drm_pan[i] = eb->drm_pan[i];
    p->wow = eb->wow;
    p->dly_time = eb->dly_time;
    p->isolator = eb->isolator;
    p->swing = eb->swing;
    p->tap = fx->tap;
    p->tank = fx->tank;
    p->loop_filt = fx->loop_filt;
    p->feedback = fx->feedback;
    p->dly_lvl = fx->dly_lvl;
    p->rev_mix = fx->rev_mix;
    p->rev_damp = fx->rev_damp;
    p->rev_tail = fx->rev_tail;
    p->dly_rev = fx->dly_rev;
    p->pump = fx->pump;
    p->wobble = fx->wobble;
    p->drum_kit = fx->drum_kit;
    p->bass_model = fx->bass_model;
    p->lvl_b = POP_LVL_B_DEF[era];
    p->lvl_c = POP_LVL_C_DEF[era];
    p->rev_b = (uint8_t)(20u + (fx->rev_mix >> 2));
    p->rev_c = (uint8_t)(22u + (fx->rev_mix >> 2));
    p->drm_dens[3] = POP_LEAD_TIMB_DEF[era];
}

